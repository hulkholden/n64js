export function writeSprite2DFixture(ram, o = {}) {
  ram.setUint32(0x100, 0x10000);
  ram.setUint32(0x104, o.tlut ? 0x20000 : 0);
  ram.setUint16(0x108, o.stride ?? 16);
  ram.setUint16(0x10a, o.width ?? 8);
  ram.setUint16(0x10c, o.height ?? 4);
  ram.setUint8(0x10e, o.fmt ?? 0);
  ram.setUint8(0x10f, o.size ?? 2);
  ram.setUint16(0x110, o.imageX ?? 0);
  ram.setUint16(0x112, o.imageY ?? 0);
  ram.setUint32(0x114, 0);
  // Asymmetric texture and palette patterns reveal wrong strides, nibble
  // alignment, vertical strips, flips and stale palette contents.
  for (let i = 0; i < 0x10000; i++) {
    ram.setUint8(0x10000 + i, ((i >> 2) * 17) ^ (i * 13));
  }
  for (let i = 0; i < 256; i++) {
    ram.setUint16(0x20000 + i * 2, (i * 6181) | 1);
  }
  sprite2DCommands(o).forEach(([a, b], i) => {
    ram.setUint32(0x200 + i * 8, a);
    ram.setUint32(0x204 + i * 8, b);
  });
}
